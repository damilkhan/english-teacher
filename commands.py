# =========================================================
# COMMANDS.PY — команды смены режима
# =========================================================
# Перенесено из консольной версии (main.py + profile_manager.switch_to_*),
# которую мы удалили. Это единственная реально полезная фича того режима:
# можно переключить Джейн из «урока» в «свободное общение» голосом,
# не лезь в настройки.
#
# Работает и для голоса, и для текста — в окне это одинаково удобно.
# Проверка строгая: команда должна быть всей репликой целиком, иначе
# обычная фраза со словом «друг» улетела бы в переключатель.
#
# Модуль чистый (без Tk и сети) — поэтому легко тестируется.
# =========================================================

MODE_LABELS = {"lesson": "Урок", "free": "Свободное общение"}

# Что можно сказать/написать, чтобы переключить режим
MODE_COMMANDS = {
    "lesson": ("урок", "заниматься", "учитель"),
    "free": ("перерыв", "отдохнем", "отдохнём", "друг"),
}

# Короткая фраза, которую Джейн произносит при переключении голосом
GREETINGS = {
    "lesson": "Welcome back to your English lesson!",
    "free": "Okay, let's just chat! What's up?",
}

# Whisper любит добавлять точку, а пользователь — восклицательный знак
_TRIM_CHARS = " \t\n\r!?.,;:—-–\"'«»"


def parse_mode_command(text):
    """Вернуть 'lesson'/'free', если реплика — команда смены режима, иначе None."""
    if not text:
        return None
    word = text.strip().lower().strip(_TRIM_CHARS).strip().lower()
    for mode, words in MODE_COMMANDS.items():
        if word in words:
            return mode
    return None


def is_mode_command(text):
    return parse_mode_command(text) is not None
