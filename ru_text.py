# -*- coding: utf-8 -*-
# =========================================================
# RU_TEXT.PY — русские числительные без ошибок («1 слово», «2 слова»)
# =========================================================
# Зачем отдельный файл: склонение нужно в РАЗНЫХ местах (карта, чат,
# сообщения окна повторения), а Tk-модуль импортировать ради одной функции
# нельзя — её тогда не проверить тестом без окна.
#
# Правило русских числительных: форма зависит от ДВУХ последних цифр.
#   1, 21, 31 …        → «слово»   (но 11 → «слов»!)
#   2–4, 22–24 …       → «слова»   (но 12–14 → «слов»)
#   0, 5–20, 25–30 …   → «слов»
# Ошибка «Давай повторим 1 слов» (найдена учеником 25.10.2026) — как раз
# следствие того, что число подставляли в готовый шаблон.

from __future__ import annotations


def plural_ru(count, one="урок", few="урока", many="уроков") -> str:
    """Форма слова для числа: 1 урок, 2 урока, 5 уроков, 11 уроков, 21 урок."""
    try:
        n = abs(int(count))
    except (TypeError, ValueError):
        return many
    if n % 10 == 1 and n % 100 != 11:
        return one
    if 2 <= n % 10 <= 4 and not (12 <= n % 100 <= 14):
        return few
    return many


def with_count(count, one, few, many) -> str:
    """«1 слово», «3 слова», «11 слов» — число вместе с правильной формой."""
    try:
        number = int(count)
    except (TypeError, ValueError):
        number = 0
    return "%d %s" % (number, plural_ru(number, one, few, many))


# Готовые наборы форм для частых слов (чтобы не повторять тройки по коду).
WORDS = ("слово", "слова", "слов")
QUESTIONS = ("вопрос", "вопроса", "вопросов")
LESSONS = ("урок", "урока", "уроков")
MISTAKES = ("ошибка", "ошибки", "ошибок")
HINTS = ("подсказка", "подсказки", "подсказок")
ATTEMPTS = ("попытка", "попытки", "попыток")
CARDS = ("карточка", "карточки", "карточек")


def words(count) -> str:
    """«1 слово» / «3 слова» / «10 слов»."""
    return with_count(count, *WORDS)


def questions(count) -> str:
    """«1 вопрос» / «10 вопросов»."""
    return with_count(count, *QUESTIONS)
